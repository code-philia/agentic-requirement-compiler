def fixed_web_runtime(workspace: Path) -> dict[str, str]:
    """Materialize fixed scaffold code; migrate known legacy code, reject customization."""
    template = Path(__file__).resolve().parents[1] / "arc-template/templates/web-react-express/backend/src/database"
    hook = "    await require('./arc_database').prepareDatabase(database); // ARC_DATABASE_PREPARE"
    result: dict[str, str] = {}
    for name in ("init_db.js", "db_runtime.js", "index.js", "seed_db.js", "test_harness.js", "prepare_e2e.js", "verify_runtime.js"):
        relative = "backend/src/database/" + name
        target = workspace / relative
        if target.is_symlink() or not target.resolve().is_relative_to(workspace.resolve()):
            raise ValueError(f"Unsafe fixed database runtime path: {relative}")
        # The verifier belongs to the compiler, not the application template.
        # Generate it on every preparation, including resumes of older workspaces.
        expected = WEB_VERIFY_RUNTIME if name == "verify_runtime.js" else (template / name).read_text(encoding="utf-8")
        if target.exists():
            original = target.read_text(encoding="utf-8")
            normalized = original.replace(hook + "\n", "") if name == "init_db.js" else original
            comparison = expected
            if name == "init_db.js":
                pattern = r"    /\*\*\n     \* Guide model instructions:\n.*?     \*/"
                replacement = "    // Fixed connection lifecycle. Schema and seeds come from ARC's JSON compiler."
                # Normalize both sides: the current template may still contain
                # the legacy guidance block. Keep materialized output unchanged.
                normalized = re.sub(pattern, replacement, normalized, count=1, flags=re.DOTALL)
                comparison = re.sub(pattern, replacement, expected, count=1, flags=re.DOTALL)
                # Known legacy initializers cached a Promise resolving to undefined.
                # Accept only that missing return; all other customizations still fail.
                promise_end = r"\n(?:    return database;\n)?  \}\)\(\);"
                fixed_end = "\n    return database;\n  })();"
                normalized = re.sub(promise_end, fixed_end, normalized, count=1)
                comparison = re.sub(promise_end, fixed_end, comparison, count=1)
            if name == "seed_db.js":
                legacy = re.sub(r"    /\*\*\n     \* Guide model instructions:\n.*?     \*/", "", original, count=1, flags=re.DOTALL)
                skeleton = """const { closeDb } = require('./init_db');
const { withTransaction } = require('./db_runtime');
async function seedDatabase() {
  return withTransaction(async ({ run, get, all, exec }) => {
    void run; void get; void all; void exec;
  });
}
"""
                prefix, separator, suffix = legacy.partition("if (require.main === module)")
                expected_suffix = expected.partition("if (require.main === module)")[2]
                if (separator and re.sub(r"\s+", "", prefix) == re.sub(r"\s+", "", skeleton)
                        and suffix == expected_suffix):
                    normalized = expected
            if normalized != comparison:
                raise ValueError(f"Database runtime differs from the fixed scaffold: {relative}; migrate custom code explicitly, not through node TDD")
        if name == "init_db.js":
            anchor = "    await runStatement(database, 'PRAGMA foreign_keys = ON;');"
            expected = expected.replace(anchor, anchor + "\n" + hook, 1)
        result[relative] = expected
    return result


def runtime_bootstrap_hook(workspace: Path, app_type: str, android_package: str) -> dict[str, str]:
    if app_type == "web":
        return fixed_web_runtime(workspace)
    if app_type == "cli":
        relative = "app/__main__.py"
        path = workspace / relative
        if not path.resolve().is_relative_to(workspace.resolve()):
            raise ValueError("CLI database bootstrap path escapes workspace")
        if not path.is_file():
            raise ValueError("CLI bootstrap requires app/__main__.py")
        source = path.read_text(encoding="utf-8")
        hook = "from .arc_database import connect_database as _arc_connect\n_arc_connect().close()  # ARC_DATABASE_PREPARE\n"
        if "# ARC_DATABASE_PREPARE" in source:
            if source.count(hook) != 1:
                raise ValueError("The compiler-owned CLI database bootstrap hook was modified")
            return {}
        # Place before application imports/entrypoint but after module docstring and future imports.
        module = ast.parse(source)
        offset = 0
        for index, statement in enumerate(module.body):
            if (index == 0 and isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Constant)
                    and isinstance(statement.value.value, str)) or (
                    isinstance(statement, ast.ImportFrom) and statement.module == "__future__"):
                offset = statement.end_lineno or statement.lineno
            else:
                break
        lines = source.splitlines(keepends=True)
        return {relative: "".join(lines[:offset]) + "\n" + hook + "\n" + "".join(lines[offset:])}
    if app_type == "android":
        manifest = ET.parse(workspace / "app/src/main/AndroidManifest.xml")
        application = manifest.getroot().find("application")
        name = application.get("{http://schemas.android.com/apk/res/android}name", "") if application is not None else ""
        if not name:
            raise ValueError("Android database bootstrap requires a manifest-declared Java Application class")
        full_name = android_package + name if name.startswith(".") else name if "." in name else android_package + "." + name
        relative = "app/src/main/java/" + full_name.replace(".", "/") + ".java"
        path = workspace / relative
        if not path.resolve().is_relative_to(workspace.resolve()):
            raise ValueError("Android database bootstrap path escapes workspace")
        if not path.is_file():
            raise ValueError("Android database bootstrap requires a Java Application source file")
        source = path.read_text(encoding="utf-8")
        hook = f"        try ({android_package}.database.ArcDatabase arcDb = new {android_package}.database.ArcDatabase(this)) {{ arcDb.getWritableDatabase(); }} // ARC_DATABASE_PREPARE"
        if "// ARC_DATABASE_PREPARE" in source:
            if source.count(hook) != 1:
                raise ValueError("The compiler-owned Android database bootstrap hook was modified")
            return {}
        pattern = r"super\.onCreate\(\);"
        if len(re.findall(pattern, source)) != 1:
            raise ValueError("Android Application source must have one super.onCreate() bootstrap anchor")
        return {relative: re.sub(pattern, lambda match: match.group(0) + "\n" + hook, source, count=1)}
    raise ValueError(f"Unknown database bootstrap application type: {app_type}")
