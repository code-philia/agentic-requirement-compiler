JS_RUNTIME = r'''// Generated by ARC DATABASE_PREPARE. Change the JSON plan through requirement sync.
'use strict';
const PROGRAM = __PROGRAM__;
function run(db, sql) {
  return new Promise((resolve, reject) => db.run(sql, error => error ? reject(error) : resolve()));
}
function all(db, sql) {
  return new Promise((resolve, reject) => db.all(sql, (error, rows) => error ? reject(error) : resolve(rows)));
}
async function prepareDatabase(db) {
  await run(db, 'PRAGMA foreign_keys = ON');
  await run(db, 'BEGIN IMMEDIATE');
  try {
    for (const table of PROGRAM.tables) {
      await run(db, table.create);
      const columns = await all(db, `PRAGMA table_info("${table.name}")`);
      for (const column of table.columns) {
        if (!columns.some(existing => existing.name === column.name)) {
          await run(db, table.add_columns[column.name]);
        }
      }
    }
    for (const sql of PROGRAM.indexes) await run(db, sql);
    for (const sql of PROGRAM.seeds) await run(db, sql);
    const violations = await all(db, 'PRAGMA foreign_key_check');
    if (violations.length) throw new Error('Database foreign key violations: ' + JSON.stringify(violations));
    await run(db, 'COMMIT');
  } catch (error) {
    await run(db, 'ROLLBACK');
    throw error;
  }
}
module.exports = { prepareDatabase };
'''


PY_RUNTIME = r'''# Generated by ARC DATABASE_PREPARE. Change records through requirement sync.
import json
import os
import sqlite3
from pathlib import Path

PROGRAM = json.loads(__PROGRAM_LITERAL__)

def prepare_database(connection):
    connection.execute("PRAGMA foreign_keys = ON")
    with connection:
        connection.execute("BEGIN IMMEDIATE")
        for table in PROGRAM["tables"]:
            connection.execute(table["create"])
            names = {row[1] for row in connection.execute('PRAGMA table_info("' + table["name"] + '")')}
            for column in table["columns"]:
                if column["name"] not in names:
                    connection.execute(table["add_columns"][column["name"]])
        for sql in PROGRAM["indexes"] + PROGRAM["seeds"]:
            connection.execute(sql)
        if connection.execute("PRAGMA foreign_key_check").fetchall():
            raise RuntimeError("Database contains foreign key violations")

def connect_database(db_path=None):
    db_path = db_path or os.environ.get("ARC_DB_FILE") or os.environ.get("DATABASE_FILE") or "database.db"
    if db_path != ":memory:":
        Path(db_path).resolve().parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(db_path)
    try:
        prepare_database(connection)
    except Exception:
        connection.close()
        raise
    return connection

if __name__ == "__main__":
    connect_database().close()
'''


JAVA_RUNTIME = r'''// Generated by ARC DATABASE_PREPARE. Do not edit.
package __PACKAGE__.database;

import android.content.Context;
import android.database.Cursor;
import android.database.sqlite.SQLiteDatabase;
import android.database.sqlite.SQLiteOpenHelper;
import org.json.JSONArray;
import org.json.JSONObject;
import java.io.ByteArrayOutputStream;
import java.io.InputStream;
import java.util.HashSet;
import java.util.Set;

/** Shared persistence boundary; getWritableDatabase prepares schema and default data. */
public final class ArcDatabase extends SQLiteOpenHelper {
    private final Context context;
    public ArcDatabase(Context context) {
        this(context, "database.db");
    }
    public ArcDatabase(Context context, String databaseName) {
        super(context.getApplicationContext(), databaseName, null, 1);
        this.context = context.getApplicationContext();
    }
    @Override public void onConfigure(SQLiteDatabase db) { db.setForeignKeyConstraintsEnabled(true); }
    @Override public void onCreate(SQLiteDatabase db) { }
    @Override public void onUpgrade(SQLiteDatabase db, int oldVersion, int newVersion) { }
    @Override public void onOpen(SQLiteDatabase db) {
        super.onOpen(db);
        db.beginTransaction();
        try (InputStream input = context.getAssets().open("arc_database.json")) {
            ByteArrayOutputStream buffer = new ByteArrayOutputStream();
            byte[] bytes = new byte[4096];
            int count;
            while ((count = input.read(bytes)) != -1) buffer.write(bytes, 0, count);
            JSONObject program = new JSONObject(buffer.toString("UTF-8"));
            JSONArray tables = program.getJSONArray("tables");
            for (int i = 0; i < tables.length(); i++) {
                JSONObject table = tables.getJSONObject(i);
                db.execSQL(table.getString("create"));
                Set<String> names = new HashSet<>();
                try (Cursor cursor = db.rawQuery("PRAGMA table_info(\"" + table.getString("name") + "\")", null)) {
                    while (cursor.moveToNext()) names.add(cursor.getString(1));
                }
                JSONArray columns = table.getJSONArray("columns");
                for (int j = 0; j < columns.length(); j++) {
                    String name = columns.getJSONObject(j).getString("name");
                    if (!names.contains(name)) db.execSQL(table.getJSONObject("add_columns").getString(name));
                }
            }
            for (String key : new String[]{"indexes", "seeds"}) {
                JSONArray statements = program.getJSONArray(key);
                for (int i = 0; i < statements.length(); i++) db.execSQL(statements.getString(i));
            }
            try (Cursor cursor = db.rawQuery("PRAGMA foreign_key_check", null)) {
                if (cursor.moveToFirst()) throw new IllegalStateException("Database foreign key violations");
            }
            db.setTransactionSuccessful();
        } catch (Exception error) {
            throw new IllegalStateException("ARC database initialization failed", error);
        } finally { db.endTransaction(); }
    }
}
'''


def render_files(plan: dict[str, Any], app_type: str, android_package: str) -> dict[str, str]:
    program = compile_plan(plan)
    encoded = json.dumps(program, ensure_ascii=True, sort_keys=True, indent=2)
    if app_type == "web":
        return {"backend/src/database/arc_database.js": JS_RUNTIME.replace("__PROGRAM__", encoded)}
    if app_type == "cli":
        return {"app/arc_database.py": PY_RUNTIME.replace("__PROGRAM_LITERAL__", repr(encoded))}
    if app_type == "android":
        return {
            "app/src/main/assets/arc_database.json": encoded + "\n",
            f"app/src/main/java/{android_package.replace('.', '/')}/database/ArcDatabase.java":
                JAVA_RUNTIME.replace("__PACKAGE__", android_package),
        }
    raise ValueError(f"No database renderer for app_type={app_type}")


def write_generated_files(workspace: Path, files: dict[str, str]) -> None:
    """Write only compiler-owned paths, checking symlink escapes before every mutation."""
    root = workspace.resolve()
    for relative, content in files.items():
        path = root / relative
        if not path.resolve().is_relative_to(root):
            raise ValueError(f"Database generated path escapes workspace: {relative}")
        path.parent.mkdir(parents=True, exist_ok=True)
        # Use an adjacent temporary file so interruption never leaves a half-written module.
        temporary = path.with_name(path.name + ".arc-tmp")
        if temporary.is_symlink():
            raise ValueError(f"Database temporary path must not be a symlink: {relative}")
        temporary.write_text(content, encoding="utf-8")
        temporary.replace(path)


def web_init_hook(workspace: Path) -> dict[str, str]:
    """Integrate with the existing scaffold without replacing its connection lifecycle."""
    path = workspace / "backend/src/database/init_db.js"
    if not path.resolve().is_relative_to(workspace.resolve()):
        raise ValueError("Database initialization path escapes workspace")
    if not path.is_file():
        raise ValueError("Web database preparation requires backend/src/database/init_db.js")
    source = path.read_text(encoding="utf-8")
    hook = "    await require('./arc_database').prepareDatabase(database); // ARC_DATABASE_PREPARE"
    if "// ARC_DATABASE_PREPARE" in source:
        if source.count(hook) != 1:
            raise ValueError("The compiler-owned database bootstrap hook was modified")
        return {}
    anchor = "    await runStatement(database, 'PRAGMA foreign_keys = ON;');"
    if source.count(anchor) != 1:
        raise ValueError("Existing DB initializer does not expose the ARC scaffold bootstrap anchor; adapt init_db.js before compiling")
    return {"backend/src/database/init_db.js": source.replace(anchor, anchor + "\n" + hook, 1)}


